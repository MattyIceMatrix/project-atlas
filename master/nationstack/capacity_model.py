#!/usr/bin/env python3
r"""NATIONSTACK capacity model: from 100 million people to GPUs, megawatts and euros.

     population --> active users --> requests --> tokens/s --> GPUs --> MW --> EUR

Every number below is an ASSUMPTION, not a fact. Change them in ASSUMPTIONS, run the script,
and the report (capacity.md) is regenerated. The point is to show the reasoning and which
assumptions dominate, not to claim precise answers.

    python master/nationstack/capacity_model.py           # print + write capacity.md
"""

from __future__ import annotations

from dataclasses import dataclass, asdict
from pathlib import Path

HERE = Path(__file__).resolve().parent

ASSUMPTIONS = {
    # people
    "population": 100_000_000,
    "monthly_active_share": 0.60,      # share of population using public AI services monthly
    "daily_active_share_of_monthly": 0.40,
    "requests_per_daily_user": 12,     # chats, document checks, service questions
    "tokens_per_request": 2_000,       # prompt + context + answer
    "peak_to_average": 3.0,            # busiest hour vs daily average
    # agents and institutions (on top of citizens)
    "institutional_token_share": 0.50, # hospitals, schools, ministries, businesses add 50% more tokens
    # serving
    "tokens_per_second_per_gpu": 2_500,  # large open model, batched, modern accelerator (assumption)
    "serving_redundancy": 1.5,         # N+1 across 3 regions, maintenance, failover
    # training and research
    "training_gpus": 12_000,           # national foundation-model + research cluster
    # power and cost
    "kw_per_gpu_all_in": 1.6,          # accelerator + host share + networking (IT load)
    "pue": 1.2,                        # data-centre power usage effectiveness
    "eur_per_gpu_capex": 30_000,       # accelerator + server share + network share
    "gpu_life_years": 5,
    "eur_per_mwh": 120,
    "opex_staff_and_ops_share": 0.25,  # staff, maintenance, software, as share of annual hardware cost
}


@dataclass
class Result:
    monthly_active_users: float
    daily_active_users: float
    tokens_per_day: float
    avg_tokens_per_second: float
    peak_tokens_per_second: float
    serving_gpus: float
    total_gpus: float
    it_power_mw: float
    facility_power_mw: float
    energy_gwh_per_year: float
    capex_eur: float
    annual_cost_eur: float
    eur_per_citizen_per_year: float


def model(a: dict) -> Result:
    mau = a["population"] * a["monthly_active_share"]
    dau = mau * a["daily_active_share_of_monthly"]
    citizen_tokens = dau * a["requests_per_daily_user"] * a["tokens_per_request"]
    tokens_day = citizen_tokens * (1 + a["institutional_token_share"])
    avg_tps = tokens_day / 86_400
    peak_tps = avg_tps * a["peak_to_average"]
    serving = peak_tps / a["tokens_per_second_per_gpu"] * a["serving_redundancy"]
    total = serving + a["training_gpus"]
    it_mw = total * a["kw_per_gpu_all_in"] / 1_000
    fac_mw = it_mw * a["pue"]
    gwh = fac_mw * 24 * 365 / 1_000
    capex = total * a["eur_per_gpu_capex"]
    hw_per_year = capex / a["gpu_life_years"]
    energy_cost = gwh * 1_000 * a["eur_per_mwh"]
    annual = hw_per_year + energy_cost + hw_per_year * a["opex_staff_and_ops_share"]
    return Result(mau, dau, tokens_day, avg_tps, peak_tps, serving, total, it_mw, fac_mw, gwh, capex,
                  annual, annual / a["population"])


def sensitivity(a: dict) -> list[tuple[str, float, float]]:
    """Change each key assumption by -50% and +100%; report annual cost per citizen."""
    rows = []
    for key in ["requests_per_daily_user", "tokens_per_request", "tokens_per_second_per_gpu",
                "monthly_active_share", "training_gpus", "eur_per_gpu_capex"]:
        low = dict(a, **{key: a[key] * 0.5})
        high = dict(a, **{key: a[key] * 2.0})
        rows.append((key, model(low).eur_per_citizen_per_year, model(high).eur_per_citizen_per_year))
    return rows


def fmt(x: float) -> str:
    for unit, div in (("bn", 1e9), ("M", 1e6), ("k", 1e3)):
        if abs(x) >= div:
            return f"{x / div:,.1f}{unit}"
    return f"{x:,.1f}"


def report(a: dict) -> str:
    r = model(a)
    d = asdict(r)
    lines = [
        "# NATIONSTACK capacity model (generated)",
        "",
        "> Generated by `capacity_model.py`. Every input is an assumption; change it and re-run.",
        "",
        "```text",
        "   100,000,000 people",
        f"        |  {a['monthly_active_share']:.0%} use public AI monthly",
        f"        v  -> {fmt(r.monthly_active_users)} monthly, {fmt(r.daily_active_users)} daily",
        f"   {fmt(r.tokens_per_day)} tokens/day  ->  peak {fmt(r.peak_tokens_per_second)} tokens/s",
        "        |",
        f"        v  -> {fmt(r.serving_gpus)} serving GPUs + {fmt(a['training_gpus'])} training GPUs",
        f"   {fmt(r.total_gpus)} GPUs  ->  {r.facility_power_mw:,.0f} MW facility power  ->  {r.energy_gwh_per_year:,.0f} GWh/yr",
        "        |",
        "        v",
        f"   EUR {fmt(r.capex_eur)} capex,  EUR {fmt(r.annual_cost_eur)}/yr all-in,  EUR {r.eur_per_citizen_per_year:,.2f} per citizen per year",
        "```",
        "",
        "## Assumptions",
        "",
        "| Assumption | Value |",
        "| --- | --- |",
    ]
    lines += [f"| `{k}` | {v:,} |" for k, v in a.items()]
    lines += ["", "## Results", "", "| Quantity | Value |", "| --- | --- |"]
    lines += [f"| {k.replace('_', ' ')} | {fmt(v)} |" for k, v in d.items()]
    lines += [
        "",
        "## Sensitivity: which assumptions matter most",
        "",
        "Annual all-in cost per citizen when one assumption is halved or doubled:",
        "",
        "| Assumption | x0.5 | x2.0 |",
        "| --- | --- | --- |",
    ]
    lines += [f"| `{k}` | EUR {lo:,.2f} | EUR {hi:,.2f} |" for k, lo, hi in sensitivity(a)]
    lines += [
        "",
        "## Reading this honestly",
        "",
        "- Accelerator price dominates, followed by usage (requests, tokens) and serving throughput per GPU.",
        "  Small, efficient national models (see LOOM, EDGEBENCH, MINICOMPILER) raise throughput and cut tokens,",
        "  so efficiency is a sovereignty strategy, not only an optimisation.",
        "- Facility power lands in the tens of megawatts: siting next to clean, firm power and heat reuse",
        "  (EN 50600, district heating) is a first-order design decision.",
        "- Edge kits (LANTERN class) keep critical services alive when national networks fail; they are not",
        "  in this compute total and should be budgeted separately.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    text = report(ASSUMPTIONS)
    (HERE / "capacity.md").write_text(text)
    print(text)
